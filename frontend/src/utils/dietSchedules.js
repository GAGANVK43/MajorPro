/**
 * Returns complete 7-day meal plan localized into the requested language.
 */
export function getLocalizedWeeklyDietPlan(language = "en", dietType = "Vegetarian", isHighRisk = false) {
  const normLang = ["en", "kn", "hi", "ta", "te", "ml"].includes(language) ? language : "en";
  const category = "highRisk"; // Standard tailored low-GI clinical plan
  const subCategory = dietType === "Vegetarian" ? "veg" : "nonVeg";
  const sourceDataset = DIET_SCHEDULES[category][subCategory];

  const localizedDataset = {};
  for (const [day, meals] of Object.entries(sourceDataset)) {
    localizedDataset[day] = {
      breakfast: meals.breakfast[normLang] || meals.breakfast.en,
      breakfastCal: meals.breakfastCal,
      lunch: meals.lunch[normLang] || meals.lunch.en,
      lunchCal: meals.lunchCal,
      dinner: meals.dinner[normLang] || meals.dinner.en,
      dinnerCal: meals.dinnerCal,
    };
  }

  return localizedDataset;
}
